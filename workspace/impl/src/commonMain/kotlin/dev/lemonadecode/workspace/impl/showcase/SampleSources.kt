  private val rateLimit = listOf(
    "import type { Request, Response, NextFunction } from 'express';",
    "import { redis } from '../server/redis';",
    "import { config } from '../config';",
    "",
    "const WINDOW_MS = 60_000;",
    "",
    "interface Bucket {",
    "  tokens: number;",
    "  updatedAt: number;",
    "}",
    "",
    "export function rateLimit() {",
    "  return async (req: Request, res: Response, next: NextFunction) => {",
    "    const apiKey = req.header('x-api-key');",
    "    if (!apiKey) return next();",
    "",
    "    const key = `rl:\${apiKey}`;",
    "    const now = Date.now();",
    "    const raw = await redis.get(key);",
    "    const bucket: Bucket = raw",
    "      ? JSON.parse(raw)",
    "      : { tokens: config.rateLimitPerMin, updatedAt: now };",
    "",
    "    const refill = ((now - bucket.updatedAt) / WINDOW_MS) * config.rateLimitPerMin;",
    "    bucket.tokens = Math.min(config.rateLimitPerMin, bucket.tokens + refill);",
    "    bucket.updatedAt = now;",
    "",
    "    if (bucket.tokens < 1) {",
    "      const retryAfter = Math.ceil(((1 - bucket.tokens) * 60) / config.rateLimitPerMin);",
    "      res.set('Retry-After', String(retryAfter));",
    "      return res.status(429).json({ error: 'rate_limited' });",
    "    }",
    "",
    "    bucket.tokens -= 1;",
    "    await redis.set(key, JSON.stringify(bucket), 'PX', WINDOW_MS);",
    "    next();",
    "  };",
    "}",
  ).map { "+$it" }

